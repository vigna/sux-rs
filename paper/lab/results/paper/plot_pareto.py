#!/usr/bin/env python3
"""Space/time trade-off plots from the CSV written by pareto.sh (or by
run.sh): prints the pgfplots code of two panels sharing the space axis, query
time and construction time, with the single-threaded rows for the given
number of keys; the configurations of each structure are joined along their sweep of
expected bucket sizes (as are the other structures, when the CSV has
sweeps for them). The
configurations that are Pareto-optimal in space, query time and construction
time at once are listed in comments. With a third argument, the same figure
is also rendered with matplotlib (for a quick look).
Usage: plot_pareto.py <csv> <number of keys> [<pdf or png>]"""
import sys, re, collections

csv, n = sys.argv[1], int(sys.argv[2])

# (variant, seed bits) -> list of (lambda, bits/key, build ns/key, query ns, name)
series = collections.defaultdict(list)
for line in open(csv):
    p = line.strip().split(',')
    if len(p) < 7 or p[0] != '1' or int(p[3]) != n:
        continue
    name, bits, build, query = p[2], float(p[4]), float(p[5]), float(p[6])
    m = re.match(r'ref (\w+) S=(\d+) l=([\d.]+)', name)
    if m:
        c, s, l = m.groups()
        variant = {'plus': 'PHast+', 'phast': 'PHast'}.get(c) or f'PHast+ wrap delta={c[1]}'
    else:
        m = re.match(r'PHast-R S=(\d+) L=\d+ R=\d+ l=([\d.]+)', name)
        s, l = m.groups()
        variant = 'PHast-R'
    series[(variant, int(s))].append((float(l), bits, build, query, f'{variant} S={s} lambda={float(l):g}'))

def macro(variant):
    m = re.match(r'PHast\+ wrap delta=(\d)', variant)
    if m:
        return rf'\PHastP wrap $\delta={m.group(1)}$'
    return {'PHast+': r'\PHastP', 'PHast': r'\PHast', 'PHast-R': r'\PHastR'}[variant]
def mark(variant, s):
    if variant == 'PHast+':
        return '*' if s == 8 else 'o'
    m = 'diamond' if variant.startswith('PHast+') else 'square' if variant == 'PHast' else 'triangle'
    return m + ('*' if s == 8 else '')
def color(variant):
    return 'black' if variant.startswith('PHast+') else 'blue!70!black' if variant == 'PHast' else 'red!70!black'
rank = ['PHast+', 'PHast+ wrap delta=1', 'PHast+ wrap delta=2', 'PHast+ wrap delta=3', 'PHast', 'PHast-R']
order = sorted(series, key=lambda k: (k[1], rank.index(k[0])))

def addplots(idx):
    out = []
    for variant, s in order:
        v = sorted(series[(variant, s)])
        style = f'mark={mark(variant, s)}, color={color(variant)}, mark size=1.8pt'
        if len(v) == 1:
            style = 'only marks, ' + style
        coords = ' '.join(f'({x[1]:.3f},{x[idx]})' for x in v)
        out.append(f'\\addplot[{style}] coordinates {{ {coords} }};')
    return '\n'.join(out)

legend = ', '.join(f'{macro(v)} ($S={s}$)' for v, s in order)
print(f'% Generated by lab/results/paper/plot_pareto.py {csv} {n}')
print(r'''\begin{tikzpicture}
\begin{axis}[
  width=0.49\textwidth, height=0.38\textwidth,
  xlabel={space [bits/key]}, ylabel={query time [ns]}, enlargelimits=0.08,
  grid=major, grid style={gray!20}, legend to name=leg:pareto, legend columns=3, legend style={font=\small, /tikz/every even column/.append style={column sep=0.5em}}]''')
print(addplots(3))
print(f'\\legend{{{legend}}}')
print(r'''\end{axis}
\end{tikzpicture}%
\begin{tikzpicture}
\begin{axis}[
  width=0.49\textwidth, height=0.38\textwidth,
  xlabel={space [bits/key]}, ylabel={construction time [ns/key]}, ymode=log, enlargelimits=0.08,
  log ticks with fixed point, ytick={50,100,200,500,1000}, grid=major, grid style={gray!20}]''')
print(addplots(2))
print(r'''\end{axis}
\end{tikzpicture}\\[1ex]
\ref{leg:pareto}''')

# Configurations that no other configuration beats in space, query time, and
# construction time at once
pts = [x for v in series.values() for x in v]
print('% Pareto-optimal in space, query time and construction time:')
for l, b, bu, q, name in sorted(pts, key=lambda x: x[1]):
    if not any(b2 <= b and bu2 <= bu and q2 <= q and (b2, bu2, q2) != (b, bu, q) for _, b2, bu2, q2, _ in pts):
        print(f'%   {name}: {b:.3f} bits/key, build {bu:.1f} ns/key, query {q:.1f} ns')

if len(sys.argv) > 3:
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    plt.rcParams.update({'font.size': 8, 'legend.fontsize': 7})
    fig, axes = plt.subplots(1, 2, figsize=(6.3, 2.6))
    mcolor = {'black': 'black', 'blue!70!black': 'tab:blue', 'red!70!black': 'tab:red'}
    mmark = {'o': 'o', 'diamond': 'D', 'square': 's', 'triangle': '^'}
    mplain = lambda v, s: mmark[mark(v, s).rstrip('*')] if mark(v, s) != '*' else 'o'
    for ax, idx, label in ((axes[0], 3, 'query time (ns)'), (axes[1], 2, 'construction time (ns/key)')):
        for variant, s in order:
            v = sorted(series[(variant, s)])
            c = mcolor[color(variant)]
            ax.plot([x[1] for x in v], [x[idx] for x in v], marker=mplain(variant, s), color=c,
                    ms=4, lw=0.8, mfc=c if s == 8 else 'white', label=f'{variant} (S={s})')
        ax.set_xlabel('bits/key')
        ax.set_ylabel(label)
        ax.grid(True, lw=0.3, alpha=0.5)
    axes[1].set_yscale('log')
    axes[0].legend(loc='best', frameon=False)
    fig.tight_layout(w_pad=1.5)
    fig.savefig(sys.argv[3])
