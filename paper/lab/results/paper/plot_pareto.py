#!/usr/bin/env python3
"""Space/time trade-off plots from the CSV written by run.sh: prints the
pgfplots code of a 2x2 figure with the single-threaded rows, (a) space vs
construction time on the largest key set and (b)-(d) space vs query time on
each key set, with one shared legend (leg:pareto). The configurations of
each structure are joined along their sweep of expected bucket sizes; PHast+
with wrapping and multiplier 1 or 2 is not plotted. The configurations that
are Pareto-optimal in space, query time and construction time at once on
the largest key set, considering all structures, are listed in comments.
With a second argument, the same figure is also rendered with matplotlib
(for a quick look).
Usage: plot_pareto.py <csv> [<pdf or png>]"""
import sys, re, collections

csv = sys.argv[1]

# The variants that are plotted
PLOTTED = ['PHast+', 'PHast+ wrap delta=3', 'PHast', 'PHast-R']

# n -> (variant, seed bits) -> list of (lambda, bits/key, build ns/key, query ns, name)
series = collections.defaultdict(lambda: collections.defaultdict(list))
for line in open(csv):
    p = line.strip().split(',')
    if len(p) < 7 or p[0] != '1':
        continue
    n, name, bits, build, query = int(p[3]), p[2], float(p[4]), float(p[5]), float(p[6])
    m = re.match(r'ref (\w+) S=(\d+) l=([\d.]+)', name)
    if m:
        c, s, l = m.groups()
        variant = {'plus': 'PHast+', 'phast': 'PHast'}.get(c) or f'PHast+ wrap delta={c[1]}'
    else:
        m = re.match(r'PHast-R S=(\d+) L=\d+ R=\d+ l=([\d.]+)', name)
        s, l = m.groups()
        variant = 'PHast-R'
    series[n][(variant, int(s))].append((float(l), bits, build, query, f'{variant} S={s} lambda={float(l):g}'))
sizes = sorted(series)
top = sizes[-1]

def macro(variant):
    m = re.match(r'PHast\+ wrap delta=(\d)', variant)
    if m:
        return rf'\PHastP wrap $\delta={m.group(1)}$'
    return {'PHast+': r'\PHastP', 'PHast': r'\PHast', 'PHast-R': r'\PHastR'}[variant]
def mark(variant, s):
    # The filled circle of pgfplots is *, not o*
    if variant == 'PHast+':
        return '*' if s == 8 else 'o'
    m = 'diamond' if variant.startswith('PHast+') else 'square' if variant == 'PHast' else 'triangle'
    return m + ('*' if s == 8 else '')
def color(variant):
    return 'black' if variant.startswith('PHast+') else 'blue!70!black' if variant == 'PHast' else 'red!70!black'
def order(n):
    return sorted((k for k in series[n] if k[0] in PLOTTED), key=lambda k: (k[1], PLOTTED.index(k[0])))

def addplots(n, idx):
    out = []
    for variant, s in order(n):
        v = sorted(series[n][(variant, s)])
        style = f'mark={mark(variant, s)}, color={color(variant)}, mark size=1.8pt'
        if len(v) == 1:
            style = 'only marks, ' + style
        coords = ' '.join(f'({x[1]:.3f},{x[idx]})' for x in v)
        out.append(f'\\addplot[{style}] coordinates {{ {coords} }};')
    return '\n'.join(out)

def keys(n):
    k = len(str(n)) - 1
    return f'$10^{{{k}}}$' if n == 10**k else f'${n}$'

# The panels: (a) construction on the largest key set, then queries on each
# key set, as (number of keys, index of the measure, y label, extra axis
# options)
panels = [(top, 2, 'construction time [ns/key]',
           'ymode=log, log ticks with fixed point, ytick={20,50,100,200,500,1000,2000}, ')]
panels += [(n, 3, 'query time [ns]', '') for n in sizes]
legend = ', '.join(f'{macro(v)} ($S={s}$)' for v, s in order(top))
print(f'% Generated by lab/results/paper/plot_pareto.py {csv}')
for i, (n, idx, ylabel, extra) in enumerate(panels):
    what = 'construction' if idx == 2 else 'queries'
    leg = (', legend to name=leg:pareto, legend columns=3, legend style={font=\\small, '
           '/tikz/every even column/.append style={column sep=0.5em}}') if i == 0 else ''
    print(r'\begin{tikzpicture}')
    print(r'\begin{axis}[')
    print(r'  width=0.49\textwidth, height=0.36\textwidth, title style={font=\small},')
    print(f'  title={{({chr(ord("a") + i)}) {what}, {keys(n)} keys}},')
    print(f'  xlabel={{space [bits/key]}}, ylabel={{{ylabel}}}, {extra}enlargelimits=0.08,')
    print(f'  grid=major, grid style={{gray!20}}{leg}]')
    print(addplots(n, idx))
    if i == 0:
        print(f'\\legend{{{legend}}}')
    print(r'\end{axis}')
    print(r'\end{tikzpicture}' + ('%' if i % 2 == 0 and i < len(panels) - 1 else r'\\[1ex]'))
print(r'\ref{leg:pareto}')

# Configurations that no other configuration beats in space, query time, and
# construction time at once, on the largest key set (all structures)
pts = [x for v in series[top].values() for x in v]
print(f'% Pareto-optimal in space, query time and construction time on {top} keys:')
for l, b, bu, q, name in sorted(pts, key=lambda x: x[1]):
    if not any(b2 <= b and bu2 <= bu and q2 <= q and (b2, bu2, q2) != (b, bu, q) for _, b2, bu2, q2, _ in pts):
        print(f'%   {name}: {b:.3f} bits/key, build {bu:.1f} ns/key, query {q:.1f} ns')

if len(sys.argv) > 2:
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    plt.rcParams.update({'font.size': 8, 'legend.fontsize': 7})
    rows = (len(panels) + 1) // 2
    fig, axes = plt.subplots(rows, 2, figsize=(6.3, 2.6 * rows), squeeze=False)
    mcolor = {'black': 'black', 'blue!70!black': 'tab:blue', 'red!70!black': 'tab:red'}
    mmark = {'o': 'o', 'diamond': 'D', 'square': 's', 'triangle': '^'}
    mplain = lambda v, s: mmark[mark(v, s).rstrip('*')] if mark(v, s) != '*' else 'o'
    for i, (n, idx, ylabel, _) in enumerate(panels):
        ax = axes[i // 2][i % 2]
        for variant, s in order(n):
            v = sorted(series[n][(variant, s)])
            c = mcolor[color(variant)]
            ax.plot([x[1] for x in v], [x[idx] for x in v], marker=mplain(variant, s), color=c,
                    ms=4, lw=0.8, mfc=c if s == 8 else 'white', label=f'{variant} (S={s})')
        ax.set_title(f'({chr(ord("a") + i)}) {"construction" if idx == 2 else "queries"}, n={n}')
        ax.set_xlabel('bits/key')
        ax.set_ylabel(ylabel)
        ax.grid(True, lw=0.3, alpha=0.5)
        if idx == 2:
            ax.set_yscale('log')
    if len(panels) % 2:
        axes[-1][-1].axis('off')
    axes[0][0].legend(loc='best', frameon=False)
    fig.tight_layout(w_pad=1.5)
    fig.savefig(sys.argv[2])
