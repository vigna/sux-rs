//! Main traits used in the implementation of succinct and compressed data
//! structures.
//!
//! All traits are re-exported at this level, so you can import them either
//! from their module or from `sux::traits`. The traits are organized in the
//! following families:
//!
//! - [`bit_vec_ops`]: [`BitLength`] (the length in bits of a bit vector) and
//!   the extension traits [`BitVecOps`] and [`BitVecOpsMut`], which provide
//!   methods such as [`get`] and [`set`] to [`BitVec`] and to anything that is
//!   `AsRef<[W]>` and implements [`BitLength`]; moreover, [`BitVecValueOps`]
//!   for reading values made of several bits, and [`AtomicBitVecOps`] for
//!   atomic bit vectors.
//! - [`bit_field_slice`]: [`BitWidth`], [`BitFieldSlice`],
//!   [`BitFieldSliceMut`], and [`AtomicBitFieldSlice`], the traits of
//!   [`BitFieldVec`] and of slices of words. Most of their methods come from
//!   [`SliceByValue`] and [`SliceByValueMut`], which are re-exported, together
//!   with the whole [`value_traits`] crate.
//! - [`rank_sel`]: ranking and selection over bit vectors ([`Rank`],
//!   [`Select`], [`SelectZero`], [`NumBits`], …).
//! - [`indexed_dict`]: positional access ([`IndexedSeq`]), access by value
//!   ([`IndexedDict`]), and successor and predecessor queries ([`Succ`],
//!   [`Pred`], …) on sequences such as [`EliasFano`].
//! - [`iter`]: iterators starting from a given position, backward,
//!   bidirectional, and unchecked iterators.
//! - [`bal_paren`]: balanced parentheses.
//!
//! This module contains also [`Backend`] and [`Word`], which describe the
//! storage of all structures, and [`TryIntoUnaligned`], which converts a
//! structure into a variant using [unaligned reads].
//!
//! The [prelude] contains [`BitLength`] and all traits in [`rank_sel`] and
//! [`iter`], but, to avoid ambiguities, only the *names* of the modules
//! [`bit_vec_ops`], [`bit_field_slice`], and [`indexed_dict`]: you need to
//! import their traits explicitly (e.g., `use
//! sux::traits::bit_field_slice::*`, or `use bit_field_slice::*` after `use
//! sux::prelude::*`).
//!
//! [`get`]: BitVecOps::get
//! [`set`]: BitVecOpsMut::set
//! [`BitVec`]: crate::bits::BitVec
//! [`BitFieldVec`]: crate::bits::BitFieldVec
//! [`EliasFano`]: crate::dict::EliasFano
//! [unaligned reads]: crate::bits#unaligned-access
//! [prelude]: crate::prelude

